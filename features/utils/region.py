# 시도/시군구 정규화(팀 표준: 시도=짧은명, 시군구=공백 정리)
# '서울특별시', '서울시', '서울' -> '서울'
def normalize_sido(s):
    if not s:
        return s

    s = str(s).strip()
    s = " ".join(s.split())  # 혹시 여러 공백/탭 섞이면 1칸으로 정리

    mapping = {
        "서울": "서울", "서울시": "서울", "서울특별시": "서울",
        "부산": "부산", "부산시": "부산", "부산광역시": "부산",
        "대구": "대구", "대구시": "대구", "대구광역시": "대구",
        "인천": "인천", "인천시": "인천", "인천광역시": "인천",
        "광주": "광주", "광주시": "광주", "광주광역시": "광주",
        "대전": "대전", "대전시": "대전", "대전광역시": "대전",
        "울산": "울산", "울산시": "울산", "울산광역시": "울산",
        "세종": "세종", "세종시": "세종", "세종특별자치시": "세종",

        "경기": "경기", "경기도": "경기",
        "강원": "강원", "강원도": "강원", "강원특별자치도": "강원", "강원시": "강원",
        "충북": "충북", "충청북도": "충북", "충북시": "충북",
        "충남": "충남", "충청남도": "충남", "충남시": "충남",
        "전북": "전북", "전라북도": "전북", "전북특별자치도": "전북", "전북시": "전북",
        "전남": "전남", "전라남도": "전남", "전남시": "전남",
        "경북": "경북", "경상북도": "경북", "경북시": "경북",
        "경남": "경남", "경상남도": "경남", "경남시": "경남",
        "제주": "제주", "제주도": "제주", "제주특별자치도": "제주", "제주시": "제주",
    }

    # 완전 일치하면 바로 표준값 리턴
    if s in mapping:
        return mapping[s]

    # 공식 접미어만 붙은 케이스 
    # 대비 접미어 제거 후 재시도
    suffixes = ["특별시", "광역시", "특별자치시", "특별자치도", "자치도", "도"]
    base = s
    for suf in suffixes:
        if base.endswith(suf):
            base = base[:-len(suf)]
            break

    base = base.strip()
    return mapping.get(base, base)

# 시군구 표준(1차): 공백만 정리하는 안전한 방식
# ex. '  수원시   영통구 ' -> '수원시 영통구'
# sido 가 주어지면 (시도, 시군구) 통합 매핑 적용 (예: 청원군 -> 청주시)
def normalize_sigungu(s, sido=None):
    if not s:
        return s

    s = str(s).strip()
    s = " ".join(s.split())

    # "OO시 OO구" / "OO시 OO군" 형태 -> "OO시"로 통합 
    parts = s.split()
    if len(parts) >= 2 and parts[0].endswith("시") and (parts[1].endswith("구") or parts[1].endswith("군")):
        s = parts[0]

    if sido:
        _sigungu_override = {
            ("충북", "청원군"): "청주시",
        }
        s = _sigungu_override.get((sido, s), s)
    return s
